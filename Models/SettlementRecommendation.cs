using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using Microsoft.EntityFrameworkCore;

namespace SimplexLawFirm.Models
{
    /// <summary>
    /// A system-generated recommendation to pursue settlement instead of continuing litigation.
    /// UC-06: Recommend Settlement Opportunity.
    /// File: Models/SettlementRecommendation.cs
    /// </summary>
    public class SettlementRecommendation
    {
        public int Id { get; set; }

        // ── Case reference ──
        public int CaseId { get; set; }
        public Case? Case { get; set; }

        // ── What triggered this evaluation ──
        public SettlementTriggerType TriggerType { get; set; }

        // ── Snapshots at time of evaluation (immutable once generated) ──

        /// <summary>Projected total cost to see the litigation through to conclusion.</summary>
        [Precision(18, 2)]
        public decimal ProjectedLitigationCost { get; set; }

        /// <summary>Likelihood of success (0.00000–1.00000), sourced from the latest CaseForecast.</summary>
        [Precision(6, 5)]
        public decimal LikelihoodOfSuccess { get; set; }

        /// <summary>Value of the matter / claim amount.</summary>
        [Precision(18, 2)]
        public decimal MatterValueSnapshot { get; set; }

        /// <summary>Expected value of continuing litigation = MatterValue × LikelihoodOfSuccess − ProjectedCost.</summary>
        [Precision(18, 2)]
        public decimal ExpectedLitigationValue { get; set; }

        /// <summary>Average historical settlement amount for comparable matters.</summary>
        [Precision(18, 2)]
        public decimal AverageComparableSettlement { get; set; }

        /// <summary>Expected value of settling = AverageComparableSettlement (net of estimated settlement costs).</summary>
        [Precision(18, 2)]
        public decimal ExpectedSettlementValue { get; set; }

        /// <summary>Number of comparable settled matters used in the analysis.</summary>
        public int ComparableMatterCount { get; set; }

        /// <summary>JSON array of comparable case summaries used for the evaluation.</summary>
        public string ComparableMattersJson { get; set; } = "[]";

        // ── System recommendation ──

        /// <summary>True when settlement EV exceeds litigation EV.</summary>
        public bool SettlementRecommended { get; set; }

        /// <summary>Human-readable rationale generated by the system.</summary>
        [MaxLength(4000)]
        public string Rationale { get; set; } = string.Empty;

        /// <summary>Suggested settlement range – low end.</summary>
        [Precision(18, 2)]
        public decimal? SuggestedSettlementLow { get; set; }

        /// <summary>Suggested settlement range – high end.</summary>
        [Precision(18, 2)]
        public decimal? SuggestedSettlementHigh { get; set; }

        // ── Attorney response (UC-06 steps 7-8) ──
        public int? AttorneyId { get; set; }
        public ApplicationUser? Attorney { get; set; }

        public SettlementRecommendationStatus Status { get; set; }

        [MaxLength(4000)]
        public string? AttorneyResponse { get; set; }

        public DateTime? AttorneyRespondedAtUtc { get; set; }

        // ── Director response (UC-06 step 9) ──
        public int? DirectorId { get; set; }
        public ApplicationUser? Director { get; set; }

        [MaxLength(4000)]
        public string? DirectorResponse { get; set; }

        public DateTime? DirectorDecidedAtUtc { get; set; }

        // ── Timestamps ──
        public DateTime CreatedAtUtc { get; set; }
        public DateTime? SupersededAtUtc { get; set; }
    }
}
